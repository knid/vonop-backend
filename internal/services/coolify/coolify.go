package coolify

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"log/slog"
	"net/http"
	"strings"
	"time"
)

var httpClient = &http.Client{Timeout: 60 * time.Second}

type Service struct {
	BaseURL         string // e.g. https://coolify.wemob.io
	Token           string
	ServerUUID      string
	ProjectUUID     string
	EnvironmentName string
	PrivateKeyUUID  string
}

func NewService(baseURL, token, serverUUID, projectUUID, environmentName, privateKeyUUID string) *Service {
	return &Service{
		BaseURL:         strings.TrimRight(baseURL, "/"),
		Token:           token,
		ServerUUID:      serverUUID,
		ProjectUUID:     projectUUID,
		EnvironmentName: environmentName,
		PrivateKeyUUID:  privateKeyUUID,
	}
}

func (s *Service) doRequest(method, path string, body any) ([]byte, error) {
	var reqBody io.Reader
	if body != nil {
		b, err := json.Marshal(body)
		if err != nil {
			return nil, fmt.Errorf("coolify: marshal: %w", err)
		}
		reqBody = bytes.NewReader(b)
	}

	req, err := http.NewRequest(method, s.BaseURL+"/api/v1"+path, reqBody)
	if err != nil {
		return nil, fmt.Errorf("coolify: create request: %w", err)
	}
	req.Header.Set("Authorization", "Bearer "+s.Token)
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}

	resp, err := httpClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("coolify: do request: %w", err)
	}
	defer resp.Body.Close()

	respBody, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, fmt.Errorf("coolify: read response: %w", err)
	}

	if resp.StatusCode >= 400 {
		bodyStr := string(respBody)
		if len(bodyStr) > 500 {
			bodyStr = bodyStr[:500]
		}
		// 4xx are expected in polling scenarios (e.g. app not running yet)
		if resp.StatusCode < 500 {
			slog.Warn("Coolify API client error", "status", resp.StatusCode, "path", path, "body", bodyStr)
		} else {
			slog.Error("Coolify API server error", "status", resp.StatusCode, "path", path, "body", bodyStr)
		}
		return nil, fmt.Errorf("coolify API error: status %d", resp.StatusCode)
	}

	return respBody, nil
}

type createAppRequest struct {
	ProjectUUID        string `json:"project_uuid"`
	ServerUUID         string `json:"server_uuid"`
	EnvironmentName    string `json:"environment_name"`
	PrivateKeyUUID     string `json:"private_key_uuid,omitempty"`
	GitRepository      string `json:"git_repository"`
	GitBranch          string `json:"git_branch"`
	BuildPack          string `json:"build_pack"`
	PortsExposes       string `json:"ports_exposes"`
	Domains            string `json:"domains"`
	InstantDeploy      bool   `json:"instant_deploy"`
	IsForceHTTPS       bool   `json:"is_force_https_enabled"`
	AutogenerateDomain bool   `json:"autogenerate_domain"`
	Name               string `json:"name"`
	LimitsMemory       string `json:"limits_memory,omitempty"`
	LimitsCPUs         string `json:"limits_cpus,omitempty"`
}

type createAppResponse struct {
	UUID string `json:"uuid"`
}

type logsResponse struct {
	Logs string `json:"logs"`
}

type envVar struct {
	Key         string `json:"key"`
	Value       string `json:"value"`
	IsBuildTime bool   `json:"is_build_time"`
}

// CreateApp creates a new application from a git repository.
// Uses private deploy key if configured, otherwise falls back to public.
// Returns the Coolify application UUID.
func (s *Service) CreateApp(name, giteaRepoURL, domain, memoryLimit, cpuLimit string) (string, error) {
	endpoint := "/applications/public"
	req := createAppRequest{
		ProjectUUID:        s.ProjectUUID,
		ServerUUID:         s.ServerUUID,
		EnvironmentName:    s.EnvironmentName,
		GitRepository:      giteaRepoURL,
		GitBranch:          "main",
		BuildPack:          "nixpacks",
		PortsExposes:       "3000",
		Domains:            "https://" + domain,
		InstantDeploy:      false,
		IsForceHTTPS:       true,
		AutogenerateDomain: false,
		Name:               name,
		LimitsMemory:       memoryLimit,
		LimitsCPUs:         cpuLimit,
	}
	if s.PrivateKeyUUID != "" {
		endpoint = "/applications/private-deploy-key"
		req.PrivateKeyUUID = s.PrivateKeyUUID
	}
	body, err := s.doRequest("POST", endpoint, req)
	if err != nil {
		return "", err
	}

	var resp createAppResponse
	if err := json.Unmarshal(body, &resp); err != nil {
		return "", fmt.Errorf("coolify: unmarshal create app: %w", err)
	}
	return resp.UUID, nil
}

// RestartApp triggers a rebuild and redeploy of the application.
func (s *Service) RestartApp(appUUID string) error {
	_, err := s.doRequest("GET", fmt.Sprintf("/applications/%s/restart", appUUID), nil)
	return err
}

// GetAppStatus returns the current status of an application.
func (s *Service) GetAppStatus(appUUID string) (string, error) {
	body, err := s.doRequest("GET", fmt.Sprintf("/applications/%s", appUUID), nil)
	if err != nil {
		return "", err
	}

	var resp map[string]any
	if err := json.Unmarshal(body, &resp); err != nil {
		return "", fmt.Errorf("coolify: unmarshal status: %w", err)
	}

	status, _ := resp["status"].(string)
	return status, nil
}

// GetAppLogs returns the application logs.
func (s *Service) GetAppLogs(appUUID string, lines int) (string, error) {
	if lines <= 0 {
		lines = 100
	}
	body, err := s.doRequest("GET", fmt.Sprintf("/applications/%s/logs?lines=%d", appUUID, lines), nil)
	if err != nil {
		return "", err
	}

	var resp logsResponse
	if err := json.Unmarshal(body, &resp); err != nil {
		return "", fmt.Errorf("coolify: unmarshal logs: %w", err)
	}
	return resp.Logs, nil
}

// DeploymentStatus holds the status and logs of a Coolify deployment.
type DeploymentStatus struct {
	Status string
	Logs   string
}

// GetLatestDeployment returns the status and logs of the most recent deployment
// for an application. Works even after a failed build removes the app.
func (s *Service) GetLatestDeployment(appUUID string) (*DeploymentStatus, error) {
	body, err := s.doRequest("GET", fmt.Sprintf("/deployments/applications/%s?take=1", appUUID), nil)
	if err != nil {
		return nil, err
	}

	var deployments []struct {
		Status string `json:"status"`
		Logs   string `json:"logs"`
	}
	if err := json.Unmarshal(body, &deployments); err != nil {
		return nil, fmt.Errorf("coolify: unmarshal deployments: %w", err)
	}
	if len(deployments) == 0 {
		return nil, fmt.Errorf("coolify: no deployments found")
	}

	return &DeploymentStatus{
		Status: deployments[0].Status,
		Logs:   deployments[0].Logs,
	}, nil
}

// SyncEnvVars sets environment variables on the application using bulk update.
// All vars are marked as build-time so they're available during `next build`.
func (s *Service) SyncEnvVars(appUUID string, desired map[string]string) error {
	var data []envVar
	for k, v := range desired {
		data = append(data, envVar{Key: k, Value: v, IsBuildTime: true})
	}

	_, err := s.doRequest("PATCH", fmt.Sprintf("/applications/%s/envs/bulk", appUUID), map[string]any{
		"data": data,
	})
	return err
}

// UpdateDomains replaces the domains for an application.
// domains should be full URLs like "https://my-app.wemob.app".
func (s *Service) UpdateDomains(appUUID string, domains []string) error {
	domainStr := strings.Join(domains, ",")
	_, err := s.doRequest("PATCH", fmt.Sprintf("/applications/%s", appUUID), map[string]any{
		"domains": domainStr,
	})
	return err
}

// DeleteApp deletes a Coolify application and its resources.
func (s *Service) DeleteApp(appUUID string) error {
	_, err := s.doRequest("DELETE", fmt.Sprintf("/applications/%s", appUUID), nil)
	return err
}
