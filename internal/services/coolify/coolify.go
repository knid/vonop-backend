package coolify

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"log/slog"
	"net/http"
	"strings"
	"time"
)

var httpClient = &http.Client{Timeout: 60 * time.Second}

type Service struct {
	BaseURL         string // e.g. https://coolify.wemob.io
	Token           string
	ServerUUID      string
	ProjectUUID     string
	EnvironmentName string
	PrivateKeyUUID  string
	WebhookSecret   string // shared secret for verifying incoming webhooks
}

func NewService(baseURL, token, serverUUID, projectUUID, environmentName, privateKeyUUID, webhookSecret string) *Service {
	return &Service{
		BaseURL:         strings.TrimRight(baseURL, "/"),
		Token:           token,
		ServerUUID:      serverUUID,
		ProjectUUID:     projectUUID,
		EnvironmentName: environmentName,
		PrivateKeyUUID:  privateKeyUUID,
		WebhookSecret:   webhookSecret,
	}
}

func (s *Service) doRequest(method, path string, body any) ([]byte, error) {
	var reqBody io.Reader
	if body != nil {
		b, err := json.Marshal(body)
		if err != nil {
			return nil, fmt.Errorf("coolify: marshal: %w", err)
		}
		reqBody = bytes.NewReader(b)
	}

	req, err := http.NewRequest(method, s.BaseURL+"/api/v1"+path, reqBody)
	if err != nil {
		return nil, fmt.Errorf("coolify: create request: %w", err)
	}
	req.Header.Set("Authorization", "Bearer "+s.Token)
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}

	resp, err := httpClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("coolify: do request: %w", err)
	}
	defer resp.Body.Close()

	respBody, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, fmt.Errorf("coolify: read response: %w", err)
	}

	if resp.StatusCode >= 400 {
		bodyStr := string(respBody)
		if len(bodyStr) > 500 {
			bodyStr = bodyStr[:500]
		}
		// 4xx are expected in polling scenarios (e.g. app not running yet)
		if resp.StatusCode < 500 {
			slog.Warn("Coolify API client error", "status", resp.StatusCode, "path", path, "body", bodyStr)
		} else {
			slog.Error("Coolify API server error", "status", resp.StatusCode, "path", path, "body", bodyStr)
		}
		return nil, fmt.Errorf("coolify API error: status %d", resp.StatusCode)
	}

	return respBody, nil
}

type createAppRequest struct {
	ProjectUUID        string `json:"project_uuid"`
	ServerUUID         string `json:"server_uuid"`
	EnvironmentName    string `json:"environment_name"`
	PrivateKeyUUID     string `json:"private_key_uuid,omitempty"`
	GitRepository      string `json:"git_repository"`
	GitBranch          string `json:"git_branch"`
	BuildPack          string `json:"build_pack"`
	PortsExposes       string `json:"ports_exposes"`
	Domains            string `json:"domains"`
	InstantDeploy      bool   `json:"instant_deploy"`
	IsForceHTTPS       bool   `json:"is_force_https_enabled"`
	AutogenerateDomain bool   `json:"autogenerate_domain"`
	Name               string `json:"name"`
	LimitsMemory       string `json:"limits_memory,omitempty"`
	LimitsCPUs         string `json:"limits_cpus,omitempty"`
}

type createAppResponse struct {
	UUID string `json:"uuid"`
}

type logsResponse struct {
	Logs string `json:"logs"`
}

type envVar struct {
	Key         string `json:"key"`
	Value       string `json:"value"`
	IsBuildTime bool   `json:"is_build_time"`
}

// CreateApp creates a new application from a git repository.
// Uses private deploy key if configured, otherwise falls back to public.
// Returns the Coolify application UUID.
func (s *Service) CreateApp(name, giteaRepoURL, domain, memoryLimit, cpuLimit string) (string, error) {
	endpoint := "/applications/public"
	req := createAppRequest{
		ProjectUUID:        s.ProjectUUID,
		ServerUUID:         s.ServerUUID,
		EnvironmentName:    s.EnvironmentName,
		GitRepository:      giteaRepoURL,
		GitBranch:          "main",
		BuildPack:          "nixpacks",
		PortsExposes:       "3000",
		Domains:            "https://" + domain,
		InstantDeploy:      false,
		IsForceHTTPS:       true,
		AutogenerateDomain: false,
		Name:               name,
		LimitsMemory:       memoryLimit,
		LimitsCPUs:         cpuLimit,
	}
	if s.PrivateKeyUUID != "" {
		endpoint = "/applications/private-deploy-key"
		req.PrivateKeyUUID = s.PrivateKeyUUID
	}
	body, err := s.doRequest("POST", endpoint, req)
	if err != nil {
		return "", err
	}

	var resp createAppResponse
	if err := json.Unmarshal(body, &resp); err != nil {
		return "", fmt.Errorf("coolify: unmarshal create app: %w", err)
	}
	return resp.UUID, nil
}

// RestartApp restarts the application container without rebuilding.
func (s *Service) RestartApp(appUUID string) error {
	_, err := s.doRequest("GET", fmt.Sprintf("/applications/%s/restart", appUUID), nil)
	return err
}

// DeployApp triggers a full rebuild and redeploy of the application.
// Use this instead of RestartApp when configuration changes (domains, etc.)
// need the proxy to be regenerated.
func (s *Service) DeployApp(appUUID string) error {
	_, err := s.doRequest("GET", fmt.Sprintf("/applications/%s/deploy", appUUID), nil)
	return err
}

// GetAppStatus returns the current status of an application.
func (s *Service) GetAppStatus(appUUID string) (string, error) {
	body, err := s.doRequest("GET", fmt.Sprintf("/applications/%s", appUUID), nil)
	if err != nil {
		return "", err
	}

	var resp map[string]any
	if err := json.Unmarshal(body, &resp); err != nil {
		return "", fmt.Errorf("coolify: unmarshal status: %w", err)
	}

	status, _ := resp["status"].(string)
	return status, nil
}

// GetAppLogs returns the application logs.
func (s *Service) GetAppLogs(appUUID string, lines int) (string, error) {
	if lines <= 0 {
		lines = 100
	}
	body, err := s.doRequest("GET", fmt.Sprintf("/applications/%s/logs?lines=%d", appUUID, lines), nil)
	if err != nil {
		return "", err
	}

	var resp logsResponse
	if err := json.Unmarshal(body, &resp); err != nil {
		return "", fmt.Errorf("coolify: unmarshal logs: %w", err)
	}
	return resp.Logs, nil
}

// DeploymentStatus holds the status and logs of a Coolify deployment.
type DeploymentStatus struct {
	Status    string
	Logs      string
	CreatedAt time.Time // when Coolify created this deployment record
}

// GetLatestDeployment returns the status and logs of the most recent deployment
// for an application. Works even after a failed build removes the app.
// If the list endpoint doesn't include logs, falls back to the individual
// deployment detail endpoint.
func (s *Service) GetLatestDeployment(appUUID string) (*DeploymentStatus, error) {
	body, err := s.doRequest("GET", fmt.Sprintf("/deployments/applications/%s?take=1", appUUID), nil)
	if err != nil {
		return nil, err
	}

	var deployments []struct {
		UUID      string `json:"uuid"`
		Status    string `json:"status"`
		Logs      string `json:"logs"`
		CreatedAt string `json:"created_at"`
	}
	if err := json.Unmarshal(body, &deployments); err != nil {
		return nil, fmt.Errorf("coolify: unmarshal deployments: %w", err)
	}
	if len(deployments) == 0 {
		return nil, fmt.Errorf("coolify: no deployments found")
	}

	dep := deployments[0]
	result := &DeploymentStatus{
		Status: dep.Status,
		Logs:   dep.Logs,
	}
	if dep.CreatedAt != "" {
		if t, err := time.Parse(time.RFC3339, dep.CreatedAt); err == nil {
			result.CreatedAt = t
		} else if t, err := time.Parse("2006-01-02T15:04:05.000000Z", dep.CreatedAt); err == nil {
			result.CreatedAt = t
		}
	}

	// If logs are empty and we have a deployment UUID, fetch individual deployment
	// detail — Coolify's list endpoint often omits full build logs.
	if result.Logs == "" && dep.UUID != "" {
		detailBody, detailErr := s.doRequest("GET", fmt.Sprintf("/deployments/%s", dep.UUID), nil)
		if detailErr == nil {
			var detail struct {
				Status string `json:"status"`
				Logs   string `json:"logs"`
			}
			if json.Unmarshal(detailBody, &detail) == nil && detail.Logs != "" {
				result.Logs = detail.Logs
				if detail.Status != "" {
					result.Status = detail.Status
				}
			}
		}
	}

	return result, nil
}

// SyncEnvVars sets environment variables on the application using bulk update.
// Only NEXT_PUBLIC_* vars are marked as build-time (needed during `next build`).
// All other vars (secrets, API keys) are runtime-only to avoid baking them into
// Docker image layers where they can be extracted.
func (s *Service) SyncEnvVars(appUUID string, desired map[string]string) error {
	var data []envVar
	for k, v := range desired {
		isBuildTime := strings.HasPrefix(k, "NEXT_PUBLIC_")
		data = append(data, envVar{Key: k, Value: v, IsBuildTime: isBuildTime})
	}

	_, err := s.doRequest("PATCH", fmt.Sprintf("/applications/%s/envs/bulk", appUUID), map[string]any{
		"data": data,
	})
	return err
}

// UpdateDomains replaces the domains for an application.
// domains should be full URLs like "https://my-app.wemob.app".
func (s *Service) UpdateDomains(appUUID string, domains []string) error {
	domainStr := strings.Join(domains, ",")
	_, err := s.doRequest("PATCH", fmt.Sprintf("/applications/%s", appUUID), map[string]any{
		"domains": domainStr,
	})
	return err
}

// StopApp stops a running Coolify application without deleting it.
func (s *Service) StopApp(appUUID string) error {
	_, err := s.doRequest("GET", fmt.Sprintf("/applications/%s/stop", appUUID), nil)
	return err
}

// DeleteApp deletes a Coolify application and its resources.
func (s *Service) DeleteApp(appUUID string) error {
	_, err := s.doRequest("DELETE", fmt.Sprintf("/applications/%s", appUUID), nil)
	return err
}

// DeploymentEvent represents an incoming Coolify webhook payload for deployment events.
type DeploymentEvent struct {
	// Coolify sends different payload shapes depending on version.
	// We accept the most common fields and fall back gracefully.
	Status          string `json:"status"`
	Type            string `json:"type"`
	ApplicationUUID string `json:"application_uuid"`
	DeploymentUUID  string `json:"deployment_uuid"`
	Logs            string `json:"logs"`

	// Coolify v4 format — uses "event" and "success" instead of "status"
	Event   string `json:"event"`   // e.g. "deployment_success", "deployment_failure"
	Success *bool  `json:"success"` // true/false
	Message string `json:"message"` // e.g. "New version successfully deployed"

	// Nested format (some Coolify versions)
	Application *struct {
		UUID string `json:"uuid"`
	} `json:"application"`
	Deployment *struct {
		UUID   string `json:"uuid"`
		Status string `json:"status"`
		Logs   string `json:"logs"`
	} `json:"deployment"`
}

// AppUUID extracts the application UUID from whichever field is populated.
func (e *DeploymentEvent) AppUUID() string {
	if e.ApplicationUUID != "" {
		return e.ApplicationUUID
	}
	if e.Application != nil && e.Application.UUID != "" {
		return e.Application.UUID
	}
	return ""
}

// DeployStatus extracts the deployment status from whichever field is populated.
func (e *DeploymentEvent) DeployStatus() string {
	// Nested deployment status (older Coolify versions)
	if e.Deployment != nil && e.Deployment.Status != "" {
		return strings.ToLower(e.Deployment.Status)
	}
	// Direct status field
	if e.Status != "" {
		return strings.ToLower(e.Status)
	}
	// Coolify v4: derive status from "event" field
	switch strings.ToLower(e.Event) {
	case "deployment_success":
		return "finished"
	case "deployment_failure":
		return "failed"
	}
	// Coolify v4 fallback: use "success" boolean
	if e.Success != nil {
		if *e.Success {
			return "finished"
		}
		return "failed"
	}
	return ""
}

// DeployLogs extracts the deployment logs from whichever field is populated.
func (e *DeploymentEvent) DeployLogs() string {
	if e.Deployment != nil && e.Deployment.Logs != "" {
		return e.Deployment.Logs
	}
	if e.Logs != "" {
		return e.Logs
	}
	return e.Message
}

// RegisterWebhook creates a custom webhook notification channel in Coolify
// so deployment events are pushed to our API. Idempotent — skips if already exists.
func (s *Service) RegisterWebhook(webhookURL string) error {
	// Check if webhook already registered
	body, err := s.doRequest("GET", "/notifications", nil)
	if err != nil {
		return fmt.Errorf("coolify: list notifications: %w", err)
	}

	var existing []struct {
		Name string `json:"name"`
	}
	if json.Unmarshal(body, &existing) == nil {
		for _, n := range existing {
			if n.Name == "wemob-deploy-webhook" {
				slog.Info("Coolify webhook already registered")
				return nil
			}
		}
	}

	// Register new webhook
	_, err = s.doRequest("POST", "/notifications", map[string]any{
		"name":                            "wemob-deploy-webhook",
		"type":                            "webhook",
		"webhook_url":                     webhookURL,
		"deployment_success_notification": true,
		"deployment_failure_notification": true,
	})
	if err != nil {
		return fmt.Errorf("coolify: register webhook: %w", err)
	}

	slog.Info("Coolify webhook registered", "url", webhookURL)
	return nil
}
