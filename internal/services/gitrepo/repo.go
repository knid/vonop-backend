// WriteFileMap atomically replaces the working tree with the provided map.
// Files not in the map are deleted from disk. Called at the end of a
// successful agent run before committing.
func (r *Repo) WriteFileMap(fileMap map[string]string) error {
	return r.WithLock(func() error {
		existing, err := r.ListFiles()
		if err != nil {
			return fmt.Errorf("list files: %w", err)
		}
		existingSet := make(map[string]bool, len(existing))
		for _, p := range existing {
			existingSet[p] = true
		}

		for path, content := range fileMap {
			if err := writeFileAtomic(filepath.Join(r.Path, path), []byte(content)); err != nil {
				return fmt.Errorf("write %s: %w", path, err)
			}
			delete(existingSet, path)
		}
		for path := range existingSet {
			full := filepath.Join(r.Path, path)
			if err := os.Remove(full); err != nil && !os.IsNotExist(err) {
				return fmt.Errorf("delete %s: %w", path, err)
			}
		}
		return nil
	})
}

// tarSubtreeSkipDirs lists directory names that TarSubtree skips wherever
// they appear in the walked tree. .git is always excluded. The rest are
// regenerable JS/Expo build artifacts that explode the tarball size when
// the worker has run npm install / expo export against the repo.
var tarSubtreeSkipDirs = map[string]struct{}{
	".git":         {},
	"node_modules": {},
	"dist":         {},
	"dist-ios":     {},
	"dist-android": {},
	".expo":        {},
	".next":        {},
	".turbo":       {},
	// ios/ + android/ are generated by expo prebuild and do not belong in the
	// canonical managed Expo source tree.
	"ios":     {},
	"android": {},
}

// TarSubtree returns a gzipped tarball containing every regular file under
// `<repo>/<prefix>`, with the prefix stripped from each entry's name.
//
// Example: if the repo contains `mobile/app/index.tsx` and `mobile/lib/api.ts`,
// TarSubtree("mobile/") returns a .tar.gz whose entries are `app/index.tsx`
// and `lib/api.ts`. The .git directory and prefix-external paths are excluded.
//
// Returns an error if prefix doesn't exist, isn't a directory, or escapes the
// repo root via .. components. Empty subtree is allowed (returns an empty but
// well-formed gzip).
func (r *Repo) TarSubtree(prefix string) ([]byte, error) {
	cleanPrefix := strings.TrimSuffix(strings.TrimPrefix(filepath.Clean(prefix), "/"), "/")
	if cleanPrefix == "" || cleanPrefix == "." || strings.HasPrefix(cleanPrefix, "..") {
		return nil, fmt.Errorf("TarSubtree: invalid prefix %q", prefix)
	}
	root := filepath.Join(r.Path, cleanPrefix)
	info, err := os.Stat(root)
	if err != nil {
		return nil, fmt.Errorf("TarSubtree: stat %q: %w", root, err)
	}
	if !info.IsDir() {
		return nil, fmt.Errorf("TarSubtree: prefix %q is not a directory", prefix)
	}

	var buf bytes.Buffer
	gw := gzip.NewWriter(&buf)
	tw := tar.NewWriter(gw)

	walkErr := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if _, skip := tarSubtreeSkipDirs[d.Name()]; skip {
				return filepath.SkipDir
			}
			return nil
		}
		if !d.Type().IsRegular() {
			return nil
		}
		rel, relErr := filepath.Rel(root, path)
		if relErr != nil {
			return fmt.Errorf("rel %q: %w", path, relErr)
		}
		entryName := filepath.ToSlash(rel)
		fi, fiErr := d.Info()
		if fiErr != nil {
			return fmt.Errorf("info %q: %w", path, fiErr)
		}
		hdr := &tar.Header{
			Name:    entryName,
			Mode:    int64(fi.Mode().Perm()),
			Size:    fi.Size(),
			ModTime: fi.ModTime(),
		}
		if err := tw.WriteHeader(hdr); err != nil {
			return fmt.Errorf("tar header %q: %w", entryName, err)
		}
		f, openErr := os.Open(path)
		if openErr != nil {
			return fmt.Errorf("open %q: %w", path, openErr)
		}
		_, copyErr := io.Copy(tw, f)
		f.Close()
		if copyErr != nil {
			return fmt.Errorf("copy %q: %w", path, copyErr)
		}
		return nil
	})
	if walkErr != nil {
		return nil, fmt.Errorf("TarSubtree: walk: %w", walkErr)
	}
	if err := tw.Close(); err != nil {
		return nil, fmt.Errorf("TarSubtree: tar close: %w", err)
	}
	if err := gw.Close(); err != nil {
		return nil, fmt.Errorf("TarSubtree: gzip close: %w", err)
	}
	return buf.Bytes(), nil
}

// Reset performs a hard reset of the working tree to the given commit hash.
// Used by the agent's failure path as a defensive clean-up.
func (r *Repo) Reset(commitHash string) error {
	return r.WithLock(func() error {
		cmd := exec.Command("git", "-C", r.Path, "reset", "--hard", commitHash)
		out, err := cmd.CombinedOutput()
		if err != nil {
			return fmt.Errorf("git reset: %w: %s", err, string(out))
		}
		return nil
	})
}

// writeFileAtomic writes data to path via tempfile + rename.
func writeFileAtomic(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".tmp-")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		os.Remove(tmpName)
		return err
	}
	if err := tmp.Close(); err != nil {
		os.Remove(tmpName)
		return err
	}
	return os.Rename(tmpName, path)
}

// NewDisposableWorktree creates a short-lived git worktree for this project,
// based on the current HEAD (detached). The worktree is placed under the
// project's directory in .worktrees/ and is completely independent of the
// main persistent checkout.
//
// This is the recommended way to perform deploy-time transformations
// (branding injection, analytics injection, defensive scaffolding) without
// ever mutating the user's canonical source.
//
// Caller must call Remove() when finished (use defer).
func (r *Repo) NewDisposableWorktree() (*Worktree, error) {
	unlock := r.service.lock(r.ProjectID)
	defer unlock()

	head, err := r.head()
	if err != nil {
		return nil, fmt.Errorf("gitrepo: get head for worktree: %w", err)
	}

	wtBase := filepath.Join(r.service.BasePath, r.ProjectID, ".worktrees")
	if err := os.MkdirAll(wtBase, 0o755); err != nil {
		return nil, fmt.Errorf("gitrepo: mkdir worktrees dir: %w", err)
	}

	wtPath, err := os.MkdirTemp(wtBase, "deploy-*")
	if err != nil {
		return nil, fmt.Errorf("gitrepo: create temp worktree dir: %w", err)
	}

	// Create the worktree from the main repo (this registers it properly with .git/worktrees)
	if err := r.service.git(r.Path, "worktree", "add", "--detach", wtPath, head); err != nil {
		_ = os.RemoveAll(wtPath)
		return nil, fmt.Errorf("gitrepo: git worktree add: %w", err)
	}

	return &Worktree{
		Path:      wtPath,
		ProjectID: r.ProjectID,
		service:   r.service,
		mainRepo:  r.Path,
	}, nil
}

// Remove destroys the worktree using the proper `git worktree remove` command
// (so git's internal tracking is cleaned) followed by filesystem removal.
// Safe to call multiple times.
func (wt *Worktree) Remove() error {
	if wt == nil || wt.Path == "" {
		return nil
	}

	// Tell git to forget the worktree (best effort)
	_ = wt.service.git(wt.mainRepo, "worktree", "remove", "--force", wt.Path)

	// Nuke the directory
	err := os.RemoveAll(wt.Path)
	wt.Path = ""
	return err
}

// ReadAllFiles reads all user files from the worktree (same filtering rules
// as Repo.ReadAllFiles: skips .git, _wemob, .gitignore, and build artifacts).
func (wt *Worktree) ReadAllFiles() (map[string]string, error) {
	if wt == nil || wt.Path == "" {
		return nil, fmt.Errorf("gitrepo: worktree not initialized")
	}

	files := make(map[string]string)
	err := filepath.WalkDir(wt.Path, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(wt.Path, path)
		if rel == "." {
			return nil
		}
		if shouldSkipDir(rel, d) {
			return filepath.SkipDir
		}
		if d.IsDir() {
			return nil
		}
		if rel == ".gitignore" {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		files[rel] = string(data)
		return nil
	})
	return files, err
}

// WriteFile writes content into the worktree (creates parent dirs as needed).
func (wt *Worktree) WriteFile(relPath string, content []byte) error {
	if wt == nil || wt.Path == "" {
		return fmt.Errorf("gitrepo: worktree not initialized")
	}
	full := filepath.Join(wt.Path, relPath)
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		return fmt.Errorf("gitrepo: mkdir in worktree: %w", err)
	}
	return os.WriteFile(full, content, 0o644)
}
