type Repo struct {
	Path      string
	ProjectID string
	service   *Service
}

// Worktree is a disposable git worktree created from a project's repository.
// It shares the object store (fast + cheap) but has a completely independent
// working tree.
//
// Intended for deploy-time source transformations (badge/analytics injection,
// defensive scaffolding like ensureNextjsRootLayout) without mutating the main
// persistent checkout used by the agent, file APIs, etc.
//
// Always call Remove() when done (defer recommended). The worktree is created
// from HEAD (detached) at the moment of creation.
type Worktree struct {
	Path      string
	ProjectID string
	service   *Service
	mainRepo  string // main checkout path (for `git worktree` commands)
}

type CommitInfo struct {
	Hash      string
	Message   string
	Timestamp time.Time
}

// WriteFile writes content to the given path within the repo.
func (r *Repo) WriteFile(path string, content []byte) error {
	fullPath := filepath.Join(r.Path, path)
	dir := filepath.Dir(fullPath)
	if err := os.MkdirAll(dir, 0755); err != nil {
		return fmt.Errorf("gitrepo: mkdir: %w", err)
	}
	return os.WriteFile(fullPath, content, 0644)
}

// ReadFile reads a file from the working tree.
func (r *Repo) ReadFile(path string) ([]byte, error) {
	return os.ReadFile(filepath.Join(r.Path, path))
}

// DeleteFile removes a file from the working tree.
func (r *Repo) DeleteFile(path string) error {
	return os.Remove(filepath.Join(r.Path, path))
}

// FileExists checks if a file exists in the working tree.
func (r *Repo) FileExists(path string) bool {
	_, err := os.Stat(filepath.Join(r.Path, path))
	return err == nil
}

// skipDirNames are directory basenames excluded from working-tree walks
// (ListFiles / ReadAllFiles). They're build artifacts, package caches, and
// generated native code that aren't user-authored — once `npm install` or
// `expo prebuild` has run inside a repo, these dirs balloon the file count by
// ~100x and were tipping API responses past 30 s. The names are conventional
// in the JS/Expo/RN/Next ecosystems and match anywhere in the tree, since
// `mobile/node_modules` is just as much noise as a top-level `node_modules`.
var skipDirNames = map[string]struct{}{
	"node_modules": {},
	".expo":        {},
	".next":        {},
	"dist":         {},
	"dist-ios":     {},
	"dist-android": {},
	"ios":          {}, // generated by `expo prebuild`; user code lives in mobile/app/
	"android":      {}, // generated by `expo prebuild`
	"web-build":    {},
	"build":        {}, // RN/CRA build output
}

// shouldSkipDir reports whether the directory at rel/d.Name() should be
// pruned from working-tree walks.
func shouldSkipDir(rel string, d fs.DirEntry) bool {
	if !d.IsDir() {
		return false
	}
	if rel == ".git" || rel == metaDir {
		return true
	}
	_, skip := skipDirNames[d.Name()]
	return skip
}

// ListFiles returns all file paths in the working tree, excluding .git/,
// _wemob/, and the build-artifact dirs in skipDirNames.
func (r *Repo) ListFiles() ([]string, error) {
	var files []string
	err := filepath.WalkDir(r.Path, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(r.Path, path)
		if rel == "." {
			return nil
		}
		if shouldSkipDir(rel, d) {
			return filepath.SkipDir
		}
		if d.IsDir() {
			return nil
		}
		if rel == ".gitignore" {
			return nil
		}
		files = append(files, rel)
		return nil
	})
	return files, err
}

// ReadAllFiles reads all files from the working tree into a map, excluding
// .git/, _wemob/, .gitignore, and the build-artifact dirs in skipDirNames.
func (r *Repo) ReadAllFiles() (map[string]string, error) {
	files := make(map[string]string)
	err := filepath.WalkDir(r.Path, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(r.Path, path)
		if rel == "." {
			return nil
		}
		if shouldSkipDir(rel, d) {
			return filepath.SkipDir
		}
		if d.IsDir() {
			return nil
		}
		if rel == ".gitignore" {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		files[rel] = string(data)
		return nil
	})
	return files, err
}

// commit is the internal, lock-free version. Caller must hold the project lock.
func (r *Repo) commit(message string) (string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), commitTimeout)
	defer cancel()

	cmd := exec.CommandContext(ctx, "git", "add", "-A")
	cmd.Dir = r.Path
	if out, err := cmd.CombinedOutput(); err != nil {
		return "", fmt.Errorf("gitrepo: git add: %s: %s", err, out)
	}

	cmd = exec.CommandContext(ctx, "git", "status", "--porcelain")
	cmd.Dir = r.Path
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("gitrepo: git status: %w", err)
	}
	if len(bytes.TrimSpace(out)) == 0 {
		return r.head()
	}

	cmd = exec.CommandContext(ctx, "git", "commit", "-m", message)
	cmd.Dir = r.Path
	if out, err := cmd.CombinedOutput(); err != nil {
		return "", fmt.Errorf("gitrepo: git commit: %s: %s", err, out)
	}

	return r.head()
}

// Commit stages all changes and creates a commit. Returns the commit hash.
// Acquires the per-project lock. Fires the service's CommitHook in a goroutine
// after the lock is released and only if commit succeeded with a real hash
// (not a no-op when the working tree is clean).
func (r *Repo) Commit(message string) (string, error) {
	unlock := r.service.lock(r.ProjectID)
	hash, err := r.commit(message)
	unlock()
	if err == nil && hash != "" && r.service.onCommit != nil {
		go r.service.onCommit(r.ProjectID)
	}
	return hash, err
}

// revert is the internal, lock-free version. Caller must hold the project lock.
func (r *Repo) revert(commitHash string) error {
	ctx, cancel := context.WithTimeout(context.Background(), commitTimeout)
	defer cancel()

	cmd := exec.CommandContext(ctx, "git", "read-tree", "--reset", "-u", commitHash)
	cmd.Dir = r.Path
	if out, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("gitrepo: read-tree: %s: %s", err, out)
	}
	return nil
}

// Revert restores the working tree to the state at the given commit hash.
// Acquires the per-project lock.
func (r *Repo) Revert(commitHash string) error {
	unlock := r.service.lock(r.ProjectID)
	defer unlock()
	return r.revert(commitHash)
}

// RevertAndCommit atomically reverts to a commit and commits the result.
// Uses a single lock acquisition to avoid deadlock. Fires the CommitHook
// asynchronously after the lock is released, like Commit().
func (r *Repo) RevertAndCommit(targetHash, commitMessage string) (string, error) {
	unlock := r.service.lock(r.ProjectID)
	if err := r.revert(targetHash); err != nil {
		unlock()
		return "", err
	}
	hash, err := r.commit(commitMessage)
	unlock()
	if err == nil && hash != "" && r.service.onCommit != nil {
		go r.service.onCommit(r.ProjectID)
	}
	return hash, err
}

// WithLock acquires the project lock and calls fn. Use for multi-step
// git operations that need atomicity (e.g., commit + revert + commit).
func (r *Repo) WithLock(fn func() error) error {
	unlock := r.service.lock(r.ProjectID)
	defer unlock()
	return fn()
}

// Tag creates a lightweight tag at the current HEAD.
func (r *Repo) Tag(name string) error {
	ctx, cancel := context.WithTimeout(context.Background(), readTimeout)
	defer cancel()

	cmd := exec.CommandContext(ctx, "git", "tag", name)
	cmd.Dir = r.Path
	if out, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("gitrepo: tag: %s: %s", err, out)
	}
	return nil
}

// Log returns the last N commits.
func (r *Repo) Log(limit int) ([]CommitInfo, error) {
	ctx, cancel := context.WithTimeout(context.Background(), readTimeout)
	defer cancel()

	cmd := exec.CommandContext(ctx, "git", "log",
		fmt.Sprintf("--max-count=%d", limit),
		"--format=%H\t%s\t%aI",
	)
	cmd.Dir = r.Path
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("gitrepo: log: %w", err)
	}

	var commits []CommitInfo
	scanner := bufio.NewScanner(bytes.NewReader(out))
	for scanner.Scan() {
		parts := strings.SplitN(scanner.Text(), "\t", 3)
		if len(parts) != 3 {
			continue
		}
		ts, _ := time.Parse(time.RFC3339, parts[2])
		commits = append(commits, CommitInfo{
			Hash:      parts[0],
			Message:   parts[1],
			Timestamp: ts,
		})
	}
	return commits, nil
}

// Diff returns the unified diff between two commits (or a commit and HEAD).
// If toHash is empty, it diffs against the current working tree.
func (r *Repo) Diff(fromHash, toHash string) (string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), readTimeout)
	defer cancel()

	args := []string{"diff", fromHash}
	if toHash != "" {
		args = append(args, toHash)
	}
	cmd := exec.CommandContext(ctx, "git", args...)
	cmd.Dir = r.Path
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("gitrepo: diff: %w", err)
	}
	return string(out), nil
}

// DiffLastCommit returns the diff of the most recent commit (what it changed).
func (r *Repo) DiffLastCommit() (string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), readTimeout)
	defer cancel()

	cmd := exec.CommandContext(ctx, "git", "diff", "HEAD~1", "HEAD")
	cmd.Dir = r.Path
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("gitrepo: diff last commit: %w", err)
	}
	return string(out), nil
}

// ChangedPathsSince returns the list of file paths changed between fromHash
// and HEAD (one path per slice entry, no leading "a/" or "b/" prefix). Used
// by the agent runner to decide whether a chat turn touched the backend/
// subtree (and therefore warrants an auto-deploy). Empty result on identical
// hashes / clean tree.
func (r *Repo) ChangedPathsSince(fromHash string) ([]string, error) {
	if fromHash == "" {
		return nil, nil
	}
	ctx, cancel := context.WithTimeout(context.Background(), readTimeout)
	defer cancel()

	cmd := exec.CommandContext(ctx, "git", "diff", "--name-only", fromHash, "HEAD")
	cmd.Dir = r.Path
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("gitrepo: diff names: %w", err)
	}
	raw := strings.Split(strings.TrimRight(string(out), "\n"), "\n")
	paths := make([]string, 0, len(raw))
	for _, p := range raw {
		if p != "" {
			paths = append(paths, p)
		}
	}
	return paths, nil
}

// ReadAllFilesAtCommit reads all files at a specific commit using git archive.
func (r *Repo) ReadAllFilesAtCommit(commitHash string) (map[string]string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), commitTimeout)
	defer cancel()

	cmd := exec.CommandContext(ctx, "git", "archive", "--format=tar", commitHash)
	cmd.Dir = r.Path
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("gitrepo: archive: %w", err)
	}

	files := make(map[string]string)
	tr := tar.NewReader(bytes.NewReader(out))
	for {
		hdr, err := tr.Next()
		if err != nil {
			break
		}
		if hdr.Typeflag != tar.TypeReg {
			continue
		}
		if strings.HasPrefix(hdr.Name, metaDir+"/") || hdr.Name == ".gitignore" {
			continue
		}
		data, err := io.ReadAll(tr)
		if err != nil {
			continue
		}
		files[hdr.Name] = string(data)
	}
	return files, nil
}

// head returns the current HEAD commit hash.
func (r *Repo) head() (string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), readTimeout)
	defer cancel()

	cmd := exec.CommandContext(ctx, "git", "rev-parse", "HEAD")
	cmd.Dir = r.Path
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("gitrepo: rev-parse HEAD: %w", err)
	}
	return strings.TrimSpace(string(out)), nil
}

// Head is the exported version.
func (r *Repo) Head() (string, error) {
	return r.head()
}

